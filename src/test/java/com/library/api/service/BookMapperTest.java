package com.library.api.service;

import com.library.api.dto.request.CreateBookRequest;
import com.library.api.dto.request.UpdateBookRequest;
import com.library.api.dto.response.BookResponse;
import com.library.api.mapper.BookMapper;
import com.library.api.model.Book;
import com.library.api.model.Library;
import com.library.api.util.TestDataFactory;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

import java.time.LocalDate;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Unit tests for BookMapper.
 * Plain JUnit 5 — NO mocks, NO Spring context.
 * Mappers are pure functions with no external dependencies.
 */
class BookMapperTest {

    private BookMapper bookMapper;

    @BeforeEach
    void setUp() {
        bookMapper = new BookMapper();
    }

    @Nested
    @DisplayName("toEntity Tests")
    class ToEntityTests {

        @Test
        @DisplayName("Should map all fields from CreateBookRequest correctly")
        void toEntity_mapsAllFieldsFromCreateBookRequestCorrectly() {
            // Arrange
            CreateBookRequest request = new CreateBookRequest();
            request.setIsbn("9780140449136");
            request.setTitle("Crime and Punishment");
            request.setAuthor("Fyodor Dostoevsky");
            request.setGenre("Classic Literature");
            request.setPublicationDate(LocalDate.of(1866, 1, 1));
            request.setAcquisitionDate(LocalDate.of(2020, 3, 15));
            request.setPages(671);
            request.setLibraryId(1L);

            // Act
            Book result = bookMapper.toEntity(request);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getIsbn()).isEqualTo("9780140449136");
            assertThat(result.getTitle()).isEqualTo("Crime and Punishment");
            assertThat(result.getAuthor()).isEqualTo("Fyodor Dostoevsky");
            assertThat(result.getGenre()).isEqualTo("Classic Literature");
            assertThat(result.getPublicationDate()).isEqualTo(LocalDate.of(1866, 1, 1));
            assertThat(result.getAcquisitionDate()).isEqualTo(LocalDate.of(2020, 3, 15));
            assertThat(result.getPages()).isEqualTo(671);
            // Library should NOT be set by mapper - service is responsible
            assertThat(result.getLibrary()).isNull();
            // ID should NOT be set - auto-generated by JPA
            assertThat(result.getId()).isNull();
        }

        @Test
        @DisplayName("Should handle null optional fields gracefully")
        void toEntity_handlesNullOptionalFieldsGracefully() {
            // Arrange
            CreateBookRequest request = new CreateBookRequest();
            request.setIsbn("9780000000001");
            request.setTitle("Minimal Book");
            request.setAuthor("Unknown Author");
            request.setLibraryId(1L);
            // genre, publicationDate, acquisitionDate, pages are null

            // Act
            Book result = bookMapper.toEntity(request);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getIsbn()).isEqualTo("9780000000001");
            assertThat(result.getTitle()).isEqualTo("Minimal Book");
            assertThat(result.getAuthor()).isEqualTo("Unknown Author");
            assertThat(result.getGenre()).isNull();
            assertThat(result.getPublicationDate()).isNull();
            assertThat(result.getAcquisitionDate()).isNull();
            assertThat(result.getPages()).isNull();
        }
    }

    @Nested
    @DisplayName("updateEntity Tests")
    class UpdateEntityTests {

        @Test
        @DisplayName("Should overwrite all fields on existing Book")
        void updateEntity_overwritesAllFieldsOnExistingBook() {
            // Arrange
            Library library = TestDataFactory.createLibrary(1L, "Test Library");
            Book existingBook = TestDataFactory.createBook(1L, "9780000000001", library);
            existingBook.setTitle("Original Title");
            existingBook.setAuthor("Original Author");
            existingBook.setGenre("Original Genre");
            existingBook.setPages(100);

            UpdateBookRequest request = new UpdateBookRequest();
            request.setIsbn("9780000000002");
            request.setTitle("Updated Title");
            request.setAuthor("Updated Author");
            request.setGenre("Updated Genre");
            request.setPublicationDate(LocalDate.of(2021, 6, 15));
            request.setAcquisitionDate(LocalDate.of(2021, 12, 1));
            request.setPages(500);
            request.setLibraryId(1L);

            // Act
            bookMapper.updateEntity(existingBook, request);

            // Assert
            assertThat(existingBook.getIsbn()).isEqualTo("9780000000002");
            assertThat(existingBook.getTitle()).isEqualTo("Updated Title");
            assertThat(existingBook.getAuthor()).isEqualTo("Updated Author");
            assertThat(existingBook.getGenre()).isEqualTo("Updated Genre");
            assertThat(existingBook.getPublicationDate()).isEqualTo(LocalDate.of(2021, 6, 15));
            assertThat(existingBook.getAcquisitionDate()).isEqualTo(LocalDate.of(2021, 12, 1));
            assertThat(existingBook.getPages()).isEqualTo(500);
            // ID should remain unchanged
            assertThat(existingBook.getId()).isEqualTo(1L);
            // Library should remain unchanged (service handles library update separately)
            assertThat(existingBook.getLibrary()).isEqualTo(library);
        }

        @Test
        @DisplayName("Should allow setting fields to null via update")
        void updateEntity_allowsSettingFieldsToNull() {
            // Arrange
            Library library = TestDataFactory.createLibrary(1L, "Test Library");
            Book existingBook = TestDataFactory.createBook(1L, "9780000000001", library);
            existingBook.setGenre("Fiction");
            existingBook.setPages(300);

            UpdateBookRequest request = new UpdateBookRequest();
            request.setIsbn("9780000000001");
            request.setTitle("Same Title");
            request.setAuthor("Same Author");
            request.setGenre(null); // Explicitly null
            request.setPublicationDate(null);
            request.setAcquisitionDate(null);
            request.setPages(null);
            request.setLibraryId(1L);

            // Act
            bookMapper.updateEntity(existingBook, request);

            // Assert
            assertThat(existingBook.getGenre()).isNull();
            assertThat(existingBook.getPublicationDate()).isNull();
            assertThat(existingBook.getAcquisitionDate()).isNull();
            assertThat(existingBook.getPages()).isNull();
        }
    }

    @Nested
    @DisplayName("toResponse Tests")
    class ToResponseTests {

        @Test
        @DisplayName("Should map all Book fields including libraryId and libraryName")
        void toResponse_mapsLibraryIdAndNameCorrectly() {
            // Arrange
            Library library = TestDataFactory.createLibrary(5L, "Downtown Library");
            Book book = new Book();
            book.setId(10L);
            book.setIsbn("9780547928227");
            book.setTitle("The Hobbit");
            book.setAuthor("J.R.R. Tolkien");
            book.setGenre("Fantasy");
            book.setPublicationDate(LocalDate.of(1937, 9, 21));
            book.setAcquisitionDate(LocalDate.of(2015, 4, 10));
            book.setPages(310);
            book.setLibrary(library);

            // Act
            BookResponse result = bookMapper.toResponse(book);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getId()).isEqualTo(10L);
            assertThat(result.getIsbn()).isEqualTo("9780547928227");
            assertThat(result.getTitle()).isEqualTo("The Hobbit");
            assertThat(result.getAuthor()).isEqualTo("J.R.R. Tolkien");
            assertThat(result.getGenre()).isEqualTo("Fantasy");
            assertThat(result.getPublicationDate()).isEqualTo(LocalDate.of(1937, 9, 21));
            assertThat(result.getAcquisitionDate()).isEqualTo(LocalDate.of(2015, 4, 10));
            assertThat(result.getPages()).isEqualTo(310);
            // Library reference fields
            assertThat(result.getLibraryId()).isEqualTo(5L);
            assertThat(result.getLibraryName()).isEqualTo("Downtown Library");
        }

        @Test
        @DisplayName("Should handle null library gracefully - libraryId and libraryName are null")
        void toResponse_handlesNullLibraryGracefully() {
            // Arrange
            Book book = new Book();
            book.setId(1L);
            book.setIsbn("9780000000001");
            book.setTitle("Orphan Book");
            book.setAuthor("Unknown");
            book.setGenre("Mystery");
            book.setLibrary(null); // No library assigned

            // Act
            BookResponse result = bookMapper.toResponse(book);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getId()).isEqualTo(1L);
            assertThat(result.getIsbn()).isEqualTo("9780000000001");
            assertThat(result.getLibraryId()).isNull();
            assertThat(result.getLibraryName()).isNull();
        }

        @Test
        @DisplayName("Should map all fields when book has complete data")
        void toResponse_mapsAllFieldsWithCompleteData() {
            // Arrange
            Library library = TestDataFactory.createLibrary(1L, "Complete Library");
            Book book = TestDataFactory.createBookWithDetails(
                    42L,
                    "9781234567890",
                    "Complete Book",
                    "Complete Author",
                    "Complete Genre",
                    LocalDate.of(2019, 7, 4),
                    LocalDate.of(2020, 1, 20),
                    456,
                    library
            );

            // Act
            BookResponse result = bookMapper.toResponse(book);

            // Assert
            assertThat(result.getId()).isEqualTo(42L);
            assertThat(result.getIsbn()).isEqualTo("9781234567890");
            assertThat(result.getTitle()).isEqualTo("Complete Book");
            assertThat(result.getAuthor()).isEqualTo("Complete Author");
            assertThat(result.getGenre()).isEqualTo("Complete Genre");
            assertThat(result.getPublicationDate()).isEqualTo(LocalDate.of(2019, 7, 4));
            assertThat(result.getAcquisitionDate()).isEqualTo(LocalDate.of(2020, 1, 20));
            assertThat(result.getPages()).isEqualTo(456);
            assertThat(result.getLibraryId()).isEqualTo(1L);
            assertThat(result.getLibraryName()).isEqualTo("Complete Library");
        }
    }
}
