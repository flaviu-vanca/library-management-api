package com.library.api.service;

import com.library.api.dto.request.CreateLibraryRequest;
import com.library.api.dto.request.UpdateLibraryRequest;
import com.library.api.dto.response.LibraryResponse;
import com.library.api.mapper.LibraryMapper;
import com.library.api.model.Book;
import com.library.api.model.Library;
import com.library.api.util.TestDataFactory;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Unit tests for LibraryMapper.
 * Plain JUnit 5 — NO mocks, NO Spring context.
 * Mappers are pure functions with no external dependencies.
 */
class LibraryMapperTest {

    private LibraryMapper libraryMapper;

    @BeforeEach
    void setUp() {
        libraryMapper = new LibraryMapper();
    }

    @Nested
    @DisplayName("toEntity Tests")
    class ToEntityTests {

        @Test
        @DisplayName("Should map all fields from CreateLibraryRequest")
        void toEntity_mapsAllFieldsFromCreateLibraryRequest() {
            // Arrange
            CreateLibraryRequest request = new CreateLibraryRequest();
            request.setName("Dublin Central Library");
            request.setAddress("123 O'Connell Street, Dublin 1");
            request.setPhone("+353-1-555-0100");
            request.setEmail("dublin.central@library.ie");
            request.setEstablishedDate(LocalDate.of(1884, 10, 15));

            // Act
            Library result = libraryMapper.toEntity(request);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getName()).isEqualTo("Dublin Central Library");
            assertThat(result.getAddress()).isEqualTo("123 O'Connell Street, Dublin 1");
            assertThat(result.getPhone()).isEqualTo("+353-1-555-0100");
            assertThat(result.getEmail()).isEqualTo("dublin.central@library.ie");
            assertThat(result.getEstablishedDate()).isEqualTo(LocalDate.of(1884, 10, 15));
            // ID should NOT be set - auto-generated by JPA
            assertThat(result.getId()).isNull();
            // Books list should be null or empty - not initialized by mapper
            assertThat(result.getBooks()).isNullOrEmpty();
        }

        @Test
        @DisplayName("Should handle null optional fields gracefully")
        void toEntity_handlesNullOptionalFieldsGracefully() {
            // Arrange
            CreateLibraryRequest request = new CreateLibraryRequest();
            request.setName("Minimal Library");
            // address, phone, email, establishedDate are null

            // Act
            Library result = libraryMapper.toEntity(request);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getName()).isEqualTo("Minimal Library");
            assertThat(result.getAddress()).isNull();
            assertThat(result.getPhone()).isNull();
            assertThat(result.getEmail()).isNull();
            assertThat(result.getEstablishedDate()).isNull();
        }
    }

    @Nested
    @DisplayName("updateEntity Tests")
    class UpdateEntityTests {

        @Test
        @DisplayName("Should update library fields from UpdateLibraryRequest")
        void updateEntity_updatesLibraryFields() {
            // Arrange
            Library existingLibrary = TestDataFactory.createLibrary(1L, "Old Name");
            existingLibrary.setAddress("Old Address");
            existingLibrary.setPhone("+1-555-0100");
            existingLibrary.setEmail("old@library.org");
            existingLibrary.setEstablishedDate(LocalDate.of(1900, 1, 1));

            UpdateLibraryRequest request = new UpdateLibraryRequest();
            request.setName("New Library Name");
            request.setAddress("456 New Street, New City");
            request.setPhone("+1-555-0999");
            request.setEmail("new@library.org");
            request.setEstablishedDate(LocalDate.of(2000, 6, 15));

            // Act
            libraryMapper.updateEntity(existingLibrary, request);

            // Assert
            assertThat(existingLibrary.getName()).isEqualTo("New Library Name");
            assertThat(existingLibrary.getAddress()).isEqualTo("456 New Street, New City");
            assertThat(existingLibrary.getPhone()).isEqualTo("+1-555-0999");
            assertThat(existingLibrary.getEmail()).isEqualTo("new@library.org");
            assertThat(existingLibrary.getEstablishedDate()).isEqualTo(LocalDate.of(2000, 6, 15));
            // ID should remain unchanged
            assertThat(existingLibrary.getId()).isEqualTo(1L);
        }

        @Test
        @DisplayName("Should preserve ID and books list when updating")
        void updateEntity_preservesIdAndBooksList() {
            // Arrange
            Library existingLibrary = TestDataFactory.createLibraryWithBooks(1L, "Library With Books", 3);
            int originalBookCount = existingLibrary.getBooks().size();

            UpdateLibraryRequest request = new UpdateLibraryRequest();
            request.setName("Updated Name");
            request.setAddress("Updated Address");

            // Act
            libraryMapper.updateEntity(existingLibrary, request);

            // Assert
            assertThat(existingLibrary.getId()).isEqualTo(1L);
            assertThat(existingLibrary.getBooks()).hasSize(originalBookCount);
            assertThat(existingLibrary.getName()).isEqualTo("Updated Name");
        }

        @Test
        @DisplayName("Should allow setting optional fields to null")
        void updateEntity_allowsSettingFieldsToNull() {
            // Arrange
            Library existingLibrary = TestDataFactory.createLibrary(1L, "Test Library");
            existingLibrary.setAddress("Has Address");
            existingLibrary.setPhone("+1-555-0100");
            existingLibrary.setEmail("has@email.com");
            existingLibrary.setEstablishedDate(LocalDate.of(1990, 1, 1));

            UpdateLibraryRequest request = new UpdateLibraryRequest();
            request.setName("Still Required");
            request.setAddress(null);
            request.setPhone(null);
            request.setEmail(null);
            request.setEstablishedDate(null);

            // Act
            libraryMapper.updateEntity(existingLibrary, request);

            // Assert
            assertThat(existingLibrary.getName()).isEqualTo("Still Required");
            assertThat(existingLibrary.getAddress()).isNull();
            assertThat(existingLibrary.getPhone()).isNull();
            assertThat(existingLibrary.getEmail()).isNull();
            assertThat(existingLibrary.getEstablishedDate()).isNull();
        }
    }

    @Nested
    @DisplayName("toResponse Tests")
    class ToResponseTests {

        @Test
        @DisplayName("Should map all Library fields and calculate totalBooks from books list")
        void toResponse_mapsAllFieldsAndCalculatesTotalBooks() {
            // Arrange
            Library library = new Library();
            library.setId(10L);
            library.setName("Cork City Library");
            library.setAddress("57 Grand Parade, Cork");
            library.setPhone("+353-21-555-0200");
            library.setEmail("cork.city@library.ie");
            library.setEstablishedDate(LocalDate.of(1892, 3, 17));

            // Add books to the library
            List<Book> books = new ArrayList<>();
            for (int i = 1; i <= 5; i++) {
                Book book = new Book();
                book.setId((long) i);
                book.setIsbn("978000000000" + i);
                book.setTitle("Book " + i);
                book.setAuthor("Author " + i);
                book.setLibrary(library);
                books.add(book);
            }
            library.setBooks(books);

            // Act
            LibraryResponse result = libraryMapper.toResponse(library);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getId()).isEqualTo(10L);
            assertThat(result.getName()).isEqualTo("Cork City Library");
            assertThat(result.getAddress()).isEqualTo("57 Grand Parade, Cork");
            assertThat(result.getPhone()).isEqualTo("+353-21-555-0200");
            assertThat(result.getEmail()).isEqualTo("cork.city@library.ie");
            assertThat(result.getEstablishedDate()).isEqualTo(LocalDate.of(1892, 3, 17));
            assertThat(result.getTotalBooks()).isEqualTo(5);
        }

        @Test
        @DisplayName("Should return totalBooks as 0 when books list is null")
        void toResponse_returnsTotalBooksZeroWhenBooksListIsNull() {
            // Arrange
            Library library = new Library();
            library.setId(1L);
            library.setName("Empty Library");
            library.setBooks(null);

            // Act
            LibraryResponse result = libraryMapper.toResponse(library);

            // Assert
            assertThat(result.getTotalBooks()).isEqualTo(0);
        }

        @Test
        @DisplayName("Should return totalBooks as 0 when books list is empty")
        void toResponse_returnsTotalBooksZeroWhenBooksListIsEmpty() {
            // Arrange
            Library library = new Library();
            library.setId(1L);
            library.setName("New Library");
            library.setBooks(new ArrayList<>());

            // Act
            LibraryResponse result = libraryMapper.toResponse(library);

            // Assert
            assertThat(result.getTotalBooks()).isEqualTo(0);
        }

        @Test
        @DisplayName("Should handle library with all null optional fields")
        void toResponse_handlesLibraryWithNullOptionalFields() {
            // Arrange
            Library library = new Library();
            library.setId(99L);
            library.setName("Minimal Library");
            // address, phone, email, establishedDate, books are null

            // Act
            LibraryResponse result = libraryMapper.toResponse(library);

            // Assert
            assertThat(result).isNotNull();
            assertThat(result.getId()).isEqualTo(99L);
            assertThat(result.getName()).isEqualTo("Minimal Library");
            assertThat(result.getAddress()).isNull();
            assertThat(result.getPhone()).isNull();
            assertThat(result.getEmail()).isNull();
            assertThat(result.getEstablishedDate()).isNull();
            assertThat(result.getTotalBooks()).isEqualTo(0);
        }
    }
}
